#!/usr/bin/env python3
"""Initialize a run directory for one Taobao browse-task session.

Sits inside the project-level skill at <workspace>/.workbuddy/skills/taobao-browse-tasks/
and writes its output into <workspace>/.taobao-task-runs/ by default, keeping
everything scoped to the current project.

Creates:
    <root>/<timestamp>/
        meta.json      - run parameters (device, modules, limits, start time)
        shots/         - screenshots
        tasks.jsonl    - one JSON object per handled task
        report.md      - human readable summary, regenerated by log_task.py

Prints a single JSON object describing the created paths.
"""

import argparse
import json
import os
import sys
from datetime import datetime

DEFAULT_ROOT = ".taobao-task-runs"  # relative to the current working directory


def main() -> int:
    parser = argparse.ArgumentParser(description="Create a run directory for Taobao browse tasks.")
    parser.add_argument(
        "--module",
        default="both",
        choices=["farm", "coins", "both"],
        help="farm=芭芭农场, coins=淘金币, both=两个都跑 (default: both)",
    )
    parser.add_argument("--device", default="", help="Android device id reported by mobile_list_available_devices")
    parser.add_argument("--max-tasks", type=int, default=150, help="Safety cap on completed task rounds (default: 150)")
    parser.add_argument("--max-minutes", type=int, default=60, help="Safety cap on wall clock minutes (default: 60)")
    parser.add_argument(
        "--dir",
        default=DEFAULT_ROOT,
        help=f"Root directory for runs, relative to CWD unless absolute (default: {DEFAULT_ROOT})",
    )
    args = parser.parse_args()

    started = datetime.now()
    stamp = started.strftime("%Y%m%d-%H%M%S")
    run_dir = os.path.abspath(os.path.join(os.path.expanduser(args.dir), stamp))
    shots_dir = os.path.join(run_dir, "shots")
    os.makedirs(shots_dir, exist_ok=True)

    meta = {
        "started_at": started.isoformat(timespec="seconds"),
        "modules": ["芭芭农场", "淘金币"] if args.module == "both" else (
            ["芭芭农场"] if args.module == "farm" else ["淘金币"]
        ),
        "device": args.device,
        "max_tasks": args.max_tasks,
        "max_minutes": args.max_minutes,
    }
    with open(os.path.join(run_dir, "meta.json"), "w", encoding="utf-8") as fh:
        json.dump(meta, fh, ensure_ascii=False, indent=2)

    tasks_log = os.path.join(run_dir, "tasks.jsonl")
    open(tasks_log, "a", encoding="utf-8").close()

    report_path = os.path.join(run_dir, "report.md")
    with open(report_path, "w", encoding="utf-8") as fh:
        fh.write(f"# 淘宝浏览任务运行记录\n\n")
        fh.write(f"- 开始时间：{meta['started_at']}\n")
        fh.write(f"- 设备：{meta['device'] or '（未指定）'}\n")
        fh.write(f"- 模块：{'、'.join(meta['modules'])}\n")
        fh.write(f"- 安全上限：最多 {meta['max_tasks']} 轮 / {meta['max_minutes']} 分钟\n\n")
        fh.write("## 任务明细\n\n")
        fh.write("| # | 模块 | 任务 | 进度 | 判定 | 结果 | 停留 | 备注 |\n")
        fh.write("|---|------|------|------|------|------|------|------|\n")

    print(
        json.dumps(
            {
                "run_dir": run_dir,
                "shots_dir": shots_dir,
                "tasks_log": tasks_log,
                "report_path": report_path,
                "meta_path": os.path.join(run_dir, "meta.json"),
                "started_at": meta["started_at"],
            },
            ensure_ascii=False,
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
