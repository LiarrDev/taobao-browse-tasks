#!/usr/bin/env python3
"""Initialize a run directory for one Taobao browse-task session.

Sits inside the project-level skill at <workspace>/.agents/skills/taobao-browse-tasks/
and writes its output into <workspace>/.taobao-task-runs/ by default, keeping
everything scoped to the current project.

Creates:
    <root>/<timestamp>/
        meta.json            - run parameters (device, modules, limits, start time)
        screen_timeout.json  - original screen_off_timeout, restored by --finish
        shots/               - screenshots
        tasks.jsonl          - one JSON object per handled task
        report.md            - human readable summary, regenerated by log_task.py

When --device is given, the phone's current screen_off_timeout is recorded and
temporarily raised to --screen-timeout-ms (default 30 min) so the screen does
not sleep mid-run. log_task.py --finish restores the original value.

Before creating the new directory it prunes old runs: anything under <root> whose
`YYYYMMDD-HHMMSS` name is older than --keep-days (default 3) is deleted, so
screenshots and reports don't pile up. Only directories named like a run and
sitting directly under <root> are ever touched — see scripts/prune_runs.py.

Prints a single JSON object describing the created paths (plus "prune": {...}).
"""

import argparse
import json
import os
import sys
from datetime import datetime

DEFAULT_ROOT = ".taobao-task-runs"  # relative to the current working directory

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
try:
    from prune_runs import prune as prune_runs  # same directory, imported by path
except ImportError:  # pragma: no cover - 缺文件时不该挡住跑任务
    prune_runs = None

try:
    from screen_timeout import save as save_screen_timeout
except ImportError:  # pragma: no cover - 缺文件时不记录，但别挡住跑任务
    save_screen_timeout = None


def main() -> int:
    parser = argparse.ArgumentParser(description="Create a run directory for Taobao browse tasks.")
    parser.add_argument(
        "--module",
        default="both",
        # TEMP(双十一临时活动): "live" 是临时模块，活动下线后连同 SKILL.md 临时章节、
        # references/temp-double11-live.md 与 README 里的临时说明一并删除。
        # TEMP(双十一赛车临时活动): "race" 同样是临时模块，活动下线后连同 SKILL.md 的
        # TEMP-DOUBLE11-RACE 标记块、references/temp-double11-race.md 一并删除。
        choices=["farm", "coins", "both", "live", "race", "signin", "blackbox", "welfare"],
        help="farm=芭芭农场, coins=淘金币, both=两个都跑 (default: both), "
             "live=双十一直播体力(临时活动, 仅用户主动触发), "
             "race=双十一赛车活动(临时活动, 仅用户主动触发), "
             "signin=淘宝签到·红包签到赚元宝(仅用户主动触发), "
             "blackbox=小黑盒集钥匙(仅用户主动触发), "
             "welfare=淘宝福利购(deeplink 入口, 仅用户主动触发)",
    )
    parser.add_argument("--device", default="", help="Android device id reported by mobile_list_available_devices")
    parser.add_argument(
        "--screen-timeout-ms",
        type=int,
        default=1800000,
        help="任务期间临时设置的熄屏时间（毫秒，0=只记录不改；默认 1800000 = 30 分钟）",
    )
    parser.add_argument(
        "--no-screen-timeout",
        action="store_true",
        help="不读取/不修改手机熄屏时间（默认会记录原值、临时调长、收尾恢复）",
    )
    parser.add_argument("--max-tasks", type=int, default=150, help="Safety cap on completed task rounds (default: 150)")
    parser.add_argument("--max-minutes", type=int, default=60, help="Safety cap on wall clock minutes (default: 60)")
    parser.add_argument(
        "--dir",
        default=DEFAULT_ROOT,
        help=f"Root directory for runs, relative to CWD unless absolute (default: {DEFAULT_ROOT})",
    )
    parser.add_argument(
        "--keep-days",
        type=int,
        default=3,
        help="建新目录前清掉 root 下超过这么多天的运行目录 (default: 3)",
    )
    parser.add_argument(
        "--no-prune",
        action="store_true",
        help="跳过旧运行目录清理（需要保留历史日志时用）",
    )
    args = parser.parse_args()

    prune_report = None
    if not args.no_prune and prune_runs is not None:
        try:
            prune_report = prune_runs(args.dir, args.keep_days, apply=True)
        except SystemExit as exc:  # root 校验失败：只记录，不让它挡住跑任务
            prune_report = {"error": str(exc)}
        except Exception as exc:  # pragma: no cover
            prune_report = {"error": repr(exc)}
        if prune_report.get("removed"):
            print(
                f"[prune] 清掉 {len(prune_report['removed'])} 个超过 {args.keep_days} 天的运行目录，"
                f"释放 {prune_report['freed_bytes'] / 1048576:.1f} MB",
                file=sys.stderr,
            )

    started = datetime.now()
    stamp = started.strftime("%Y%m%d-%H%M%S")
    run_dir = os.path.abspath(os.path.join(os.path.expanduser(args.dir), stamp))
    shots_dir = os.path.join(run_dir, "shots")
    os.makedirs(shots_dir, exist_ok=True)

    screen_state = None
    if args.device and not args.no_screen_timeout and save_screen_timeout is not None:
        try:
            screen_state = save_screen_timeout(
                args.device, run_dir, applied_ms=args.screen_timeout_ms or None
            )
        except Exception as exc:  # 设备离线 / adb 缺失：只警告，不挡跑任务
            screen_state = {"ok": False, "error": repr(exc)}
        if screen_state.get("ok"):
            applied = screen_state.get("applied_ms")
            extra = f"，任务期设为 {applied}ms" if applied else "（未修改）"
            print(
                f"[screen] 已记录原熄屏时间 {screen_state['original_ms']}ms{extra}；"
                "log_task.py --finish 时自动恢复",
                file=sys.stderr,
            )
        else:
            print(f"[screen] 熄屏时间记录失败：{screen_state.get('error')}", file=sys.stderr)

    # TEMP(双十一临时活动): "live" 映射随临时模块一起删除即可。
    # TEMP(双十一赛车临时活动): "race" 映射同样随临时模块一起删除即可。
    module_names = {
        "both": ["芭芭农场", "淘金币"],
        "farm": ["芭芭农场"],
        "coins": ["淘金币"],
        "live": ["直播体力"],
        "race": ["赛车活动"],
        "signin": ["淘宝签到"],
        "blackbox": ["小黑盒"],
        "welfare": ["淘宝福利购"],
    }
    meta = {
        "started_at": started.isoformat(timespec="seconds"),
        "modules": module_names[args.module],
        "device": args.device,
        "max_tasks": args.max_tasks,
        "max_minutes": args.max_minutes,
        "screen_timeout_original_ms": (screen_state or {}).get("original_ms"),
        "screen_timeout_applied_ms": (screen_state or {}).get("applied_ms"),
    }
    with open(os.path.join(run_dir, "meta.json"), "w", encoding="utf-8") as fh:
        json.dump(meta, fh, ensure_ascii=False, indent=2)

    tasks_log = os.path.join(run_dir, "tasks.jsonl")
    open(tasks_log, "a", encoding="utf-8").close()

    report_path = os.path.join(run_dir, "report.md")
    with open(report_path, "w", encoding="utf-8") as fh:
        fh.write(f"# 淘宝浏览任务运行记录\n\n")
        fh.write(f"- 开始时间：{meta['started_at']}\n")
        fh.write(f"- 设备：{meta['device'] or '（未指定）'}\n")
        fh.write(f"- 模块：{'、'.join(meta['modules'])}\n")
        fh.write(f"- 安全上限：最多 {meta['max_tasks']} 轮 / {meta['max_minutes']} 分钟\n\n")
        fh.write("## 任务明细\n\n")
        fh.write("| # | 模块 | 任务 | 进度 | 判定 | 结果 | 停留 | 备注 |\n")
        fh.write("|---|------|------|------|------|------|------|------|\n")

    print(
        json.dumps(
            {
                "run_dir": run_dir,
                "shots_dir": shots_dir,
                "tasks_log": tasks_log,
                "report_path": report_path,
                "meta_path": os.path.join(run_dir, "meta.json"),
                "started_at": meta["started_at"],
                "prune": prune_report,
                "screen_timeout": screen_state,
            },
            ensure_ascii=False,
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
